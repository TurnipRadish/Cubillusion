def dict_to_directories(data: dict, parent_path=""):
    """
    递归将字典结构转换为文件系统目录和文件
    :param data: 字典结构，键为目录/文件名，值为子字典（目录）或字符串（文件内容）
    :param parent_path: 父目录路径，默认为当前目录
    """
    for name, content in data.items():
        current_path = os.path.join(parent_path, name)
        
        if isinstance(content, dict):
            # 创建目录并递归处理子字典
            os.makedirs(current_path, exist_ok=True)
            dict_to_directories(content, current_path)
        elif isinstance(content, str):
          # 创建文件并写入内容（自动添加换行符）
          try:
              with open(current_path, 'w', encoding='utf-8') as f:
                  f.write(content + '\n')  # 确保内容以换行符结尾
          except (IOError, PermissionError) as e:
              print(f"文件创建失败: {current_path}, 错误: {e}")
        elif content != None and isinstance(content, object):
          try:
              content.gen(current_path)
          except (IOError, PermissionError) as e:
              print(f"文件创建失败: {current_path}, 错误: {e}")
        else:
          if content == None:
            return
          else:
            print(f"警告: 忽略不支持的类型 {type(content)} (路径: {current_path})")

