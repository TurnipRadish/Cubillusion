  def add_advancements(self):
    pass
    return {}

  def gen(self, out_path: str, namespace: str):
    if not os.path.exists(out_path):
      raise FileExistsError(f'路径不存在：{out_path}')
    
    pack_path = os.path.join(out_path, self.pack_name) 
    if os.path.exists(pack_path):
      shutil.rmtree(pack_path)
    if not os.path.exists(pack_path):
      os.makedirs(pack_path)
      
    mcfunctions = self.add_functions()
    advancements = self.add_advancements()
    
    if mcfunctions:
      self.data[namespace]['function'] = mcfunctions
    if advancements:
      self.data[namespace]['advancement'] = advancements

    pack_structure = {
      "data": self.data,
      "pack.mcmeta": json.dumps(self.pack_mcmeta, indent=2)
    }
    
    dict_to_directories(pack_structure, pack_path)  
  
